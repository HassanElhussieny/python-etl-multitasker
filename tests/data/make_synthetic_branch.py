"""Generate ``branch_a_compact.txt``: a SYNTHETIC ERP export (235 documents) used by the regression tests.

Every value is fictional: seeded random amounts, customer codes 900001-900125, document numbers from 50001. Only the
*shape* mirrors a real export (sales/returns per day, three document series, discounts with net = gross - pharmacy -
distributor - cash discounts), so the tests exercise the same situations: returns on some days, no return on
08/10 and 18/10, nothing dated after 18/10. Run ``python tests/data/make_synthetic_branch.py`` to rebuild it.
"""

from __future__ import annotations

import random
from decimal import Decimal
from pathlib import Path

#: (day, sales count, returns count) between 26/09/2026 and 18/10/2026
SCHEDULE = [
    ("26-09-2026", 5, 1), ("27-09-2026", 2, 0), ("01-10-2026", 24, 5), ("03-10-2026", 0, 2), ("04-10-2026", 17, 1),
    ("05-10-2026", 3, 1), ("06-10-2026", 1, 0), ("07-10-2026", 5, 0), ("08-10-2026", 5, 0), ("10-10-2026", 9, 1),
    ("11-10-2026", 9, 5), ("12-10-2026", 14, 0), ("13-10-2026", 5, 0), ("14-10-2026", 37, 0), ("15-10-2026", 58, 0),
    ("17-10-2026", 9, 0), ("18-10-2026", 16, 0),
]
OUT = Path(__file__).with_name("branch_a_compact.txt")


def money(rng: random.Random, low: int, high: int) -> Decimal:
    return Decimal(rng.randint(low * 100, high * 100)) / 100


def build(seed: int = 20261122) -> list[str]:
    rng = random.Random(seed)
    customers = [str(900001 + i) for i in range(125)]
    lines, doc = [], 50001
    used = set()
    for day, sales, returns in SCHEDULE:
        for kind in ["S"] * sales + ["R"] * returns:
            # every customer appears at least once, then random ones
            free = [c for c in customers if c not in used]
            cust = free[0] if free and rng.random() < 0.6 else rng.choice(customers)
            used.add(cust)
            series = "93" if kind == "S" and rng.random() < 0.95 else ("94" if kind == "R" else "96")
            gross = money(rng, 150, 25000)
            pharm = (gross * Decimal(rng.choice([5, 8, 10, 12])) / 100).quantize(Decimal("0.01")) if rng.random() < 0.9 else Decimal("0")
            dist = money(rng, 10, 400) if rng.random() < 0.45 else Decimal("0")
            cash = money(rng, 5, 300) if rng.random() < 0.4 else Decimal("0")
            net = gross - pharm - dist - cash
            sign = -1 if kind == "R" else 1
            vals = [v * sign for v in (gross, pharm, dist, cash, net)]
            lines.append("|".join([day, kind, str(doc), series, cust, *(f"{v:.2f}" for v in vals)]))
            doc += 1
    return lines


if __name__ == "__main__":
    header = ["# SYNTHETIC test data (fictional values) - generated by make_synthetic_branch.py.",
              "# date|S/R|document|series|customer|gross|pharmacy discount|distributor discount|cash discount|net"]
    OUT.write_text("\n".join(header + build()) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
